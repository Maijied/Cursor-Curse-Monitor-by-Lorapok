#!/usr/bin/env node
/**
 * Generate post-merge procedure retrospective for a merged PR.
 *
 *   node scripts/procedure-finalize-pr.mjs --pr 104
 *   GITHUB_PR_NUMBER=104 node scripts/procedure-finalize-pr.mjs
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadProcedureConfig, procedureDir, slugify } from "./lib/procedure-config.mjs";

function parseArgs(argv) {
  let pr = process.env.GITHUB_PR_NUMBER ? Number(process.env.GITHUB_PR_NUMBER) : 0;
  let outDir = procedureDir();
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--pr" && argv[i + 1]) pr = Number(argv[++i]);
    else if (arg === "--out-dir" && argv[i + 1]) outDir = argv[++i];
    else if (arg === "--help" || arg === "-h") {
      console.log("Usage: node scripts/procedure-finalize-pr.mjs --pr <number>");
      process.exit(0);
    }
  }
  if (!pr || Number.isNaN(pr)) {
    console.error("Missing --pr or GITHUB_PR_NUMBER");
    process.exit(1);
  }
  return { pr, outDir };
}

function ghJson(args) {
  const result = spawnSync("gh", args, { encoding: "utf8" });
  if (result.status !== 0) {
    console.error(result.stderr || result.stdout);
    process.exit(result.status ?? 1);
  }
  return JSON.parse(result.stdout);
}

const { pr, outDir } = parseArgs(process.argv);
const config = loadProcedureConfig();
const prData = ghJson([
  "pr",
  "view",
  String(pr),
  "--repo",
  `${config.owner}/${config.repo}`,
  "--json",
  "title,body,url,mergedAt,mergeCommit,headRefName,baseRefName,additions,deletions,changedFiles,commits,statusCheckRollup,reviews",
]);

const slug = slugify(prData.title || `pr-${pr}`);
const fileName = `pr-${pr}_${slug}_merged.md`;
const filePath = resolve(outDir, fileName);

const checks = (prData.statusCheckRollup ?? [])
  .map((c) => `- ${c.name ?? c.context}: ${c.conclusion ?? c.state ?? "unknown"}`)
  .join("\n");

const commitLines = (prData.commits ?? [])
  .slice(0, 30)
  .map((c) => `- \`${(c.oid ?? c.commit?.oid ?? "").slice(0, 7)}\` ${c.messageHeadline ?? c.message ?? ""}`)
  .join("\n");

const reviewLines = (prData.reviews ?? [])
  .map((r) => `- ${r.author?.login ?? "unknown"}: ${r.state}`)
  .join("\n");

const mergedAt = prData.mergedAt ?? new Date().toISOString();

const markdown = `# PR #${pr} merged — ${prData.title}

**Merged:** ${mergedAt}  
**URL:** ${prData.url}  
**Branch:** \`${prData.headRefName}\` → \`${prData.baseRefName}\`  
**Stats:** +${prData.additions} / -${prData.deletions} (${prData.changedFiles} files)

---

## Commits

${commitLines || "_No commit list available._"}

---

## CI checks

${checks || "_No check rollup available._"}

---

## Reviews

${reviewLines || "_No reviews recorded._"}

---

## Retrospective notes

_Auto-generated by \`scripts/procedure-finalize-pr.mjs\`. Append manual verification (Tier C) and deploy notes below._

### Post-merge verification

- [ ] Admin deploy (if \`website/admin/functions\` changed)
- [ ] Production smoke documented in linked procedure file
- [ ] GitHub issue closed

---

## PR body (excerpt)

${String(prData.body ?? "").slice(0, 2000)}
`;

writeFileSync(filePath, markdown, "utf8");
console.log(filePath);

function gh(args) {
  return spawnSync("gh", args, { encoding: "utf8" });
}

// Comment on PR when running in CI
if (process.env.GITHUB_ACTIONS === "true") {
  const comment = [
    "## Procedure retrospective",
    "",
    `Merged procedure log: \`procedure/${fileName}\``,
    "",
    `+${prData.additions} / -${prData.deletions} across ${prData.changedFiles} files.`,
    "",
    "Download the full retrospective from workflow artifacts.",
  ].join("\n");
  const commentResult = gh([
    "pr",
    "comment",
    String(pr),
    "--repo",
    `${config.owner}/${config.repo}`,
    "--body",
    comment,
  ]);
  if (commentResult.status !== 0) {
    console.error(commentResult.stderr || commentResult.stdout);
    process.exit(commentResult.status ?? 1);
  }
}
