#!/usr/bin/env node
/**
 * Direct main push — sync artifacts, push main, procedure/issue/PR, optional deploy.
 *
 * Fast dev path (admin hotfix, ~2–4 min local deploy):
 *   npm run push:main:admin -- --title "fix(admin): rbac subscribers"
 *
 * Full CI deploy-infra (admin + website + mail setup):
 *   npm run push:main:full -- --title "ops: mail + admin refresh"
 *
 * Merge feature branch then push:
 *   npm run push:main:admin -- --title "…" --from feat/my-branch
 *
 * Requires: gh auth, on branch main (or use --from), committed code changes.
 */
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadProcedureConfig } from "./lib/procedure-config.mjs";

const DEPLOY_INFRA_ACTION =
  "deploy-infra - Deploy Mission Control admin & marketing site";

/** Files regenerated by site:data / site:seo — safe to auto-commit with --sync. */
export const SYNC_ARTIFACT_PATHS = [
  "website/site-data.json",
  "website/seo.json",
  "website/sitemap.xml",
  "website/robots.txt",
  "website/visitor-stats.json",
];

export function parseArgs(argv) {
  const out = {
    title: "",
    component: "",
    fromBranch: "",
    sync: false,
    deployWebsite: false,
    deployAdmin: false,
    deployFull: false,
    watchCi: false,
    skipPush: false,
    dryRun: false,
  };
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--dry-run") out.dryRun = true;
    else if (arg === "--skip-push") out.skipPush = true;
    else if (arg === "--sync") out.sync = true;
    else if (arg === "--watch-ci") out.watchCi = true;
    else if (arg === "--deploy-website") out.deployWebsite = true;
    else if (arg === "--deploy-admin") out.deployAdmin = true;
    else if (arg === "--deploy-full") out.deployFull = true;
    else if (arg === "--from" && argv[i + 1]) out.fromBranch = argv[++i];
    else if (arg === "--title" && argv[i + 1]) out.title = argv[++i];
    else if (arg === "--component" && argv[i + 1]) out.component = argv[++i];
    else if (arg === "--help" || arg === "-h") {
      console.log(`Usage: node scripts/direct-main-push.mjs --title "Task title" [options]

Options:
  --component <tag>     Label: website | admin | extension | browser
  --from <branch>       Merge branch into main before sync/push (checkout main first)
  --sync                Regenerate site-data + seo; auto-commit sync artifacts if changed
  --deploy-admin        After push, run npm run admin:deploy:fast (local, ~1–3 min)
  --deploy-website      After push, dispatch deploy-infra (marketing site only)
  --deploy-full         After push, dispatch deploy-infra (admin + website + mail)
  --watch-ci            After push, gh run watch on latest ci-cd.yml
  --skip-push           Track only (issue + PR + sync); do not git push
  --dry-run             Print planned steps only

npm shortcuts:
  push:main:admin   → --component admin --sync --deploy-admin --watch-ci
  push:main:full    → --sync --deploy-full --watch-ci
  push:main:website → --component website --deploy-website
`);
      process.exit(0);
    }
  }
  if (!out.title.trim()) {
    console.error("Missing required --title");
    process.exit(1);
  }
  if (out.deployFull) {
    out.deployWebsite = true;
    out.deployAdmin = false;
  }
  return out;
}

function run(cmd, args, opts = {}) {
  const result = spawnSync(cmd, args, {
    encoding: "utf8",
    stdio: opts.inherit ? "inherit" : "pipe",
    cwd: opts.cwd,
    env: process.env,
  });
  if (result.status !== 0 && !opts.allowFail) {
    const err = result.stderr?.trim() || result.stdout?.trim() || `${cmd} failed`;
    throw new Error(err);
  }
  return result;
}

function gh(args, opts = {}) {
  const result = run("gh", args, { ...opts, allowFail: opts.allowFail });
  return (result.stdout ?? "").trim();
}

function currentBranch() {
  return run("git", ["rev-parse", "--abbrev-ref", "HEAD"]).stdout.trim();
}

function shortSha(ref = "HEAD") {
  return run("git", ["rev-parse", "--short", ref]).stdout.trim();
}

function porcelainStatus() {
  return run("git", ["status", "--porcelain"]).stdout.trim();
}

function isSyncArtifactPath(path) {
  return SYNC_ARTIFACT_PATHS.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));
}

function assertCleanOrSyncOnly() {
  const status = porcelainStatus();
  if (!status) return;
  const lines = status.split("\n").filter(Boolean);
  const nonSync = lines.filter((line) => {
    const path = line.slice(3).trim();
    return !isSyncArtifactPath(path);
  });
  if (nonSync.length) {
    console.error("Working tree not clean. Commit code changes first, then re-run.");
    console.error(nonSync.slice(0, 8).join("\n"));
    process.exit(1);
  }
}

function runSiteSync() {
  console.log("→ Sync site-data + SEO (live marketplace APIs)…");
  run("npm", ["run", "site:data"], { inherit: true });
  run("npm", ["run", "site:seo"], { inherit: true });
}

function commitSyncArtifactsIfChanged() {
  const changed = porcelainStatus()
    .split("\n")
    .filter(Boolean)
    .map((line) => line.slice(3).trim())
    .filter((path) => isSyncArtifactPath(path));
  if (!changed.length) {
    console.log("  Sync artifacts unchanged — no commit needed.");
    return false;
  }
  console.log("→ Commit sync artifacts…");
  run("git", ["add", ...SYNC_ARTIFACT_PATHS], { inherit: true });
  run(
    "git",
    [
      "commit",
      "-m",
      "chore: sync site-data and SEO before direct main push",
    ],
    { inherit: true },
  );
  return true;
}

function mergeFromBranch(branch) {
  console.log(`→ Merge ${branch} into main…`);
  run("git", ["fetch", "origin", "main"], { inherit: true, allowFail: true });
  const local = run("git", ["rev-parse", "--verify", branch], { allowFail: true });
  if (local.status !== 0) {
    run("git", ["fetch", "origin", branch], { inherit: true });
  }
  run("git", ["merge", "--no-ff", branch, "-m", `merge: ${branch} for direct main push`], {
    inherit: true,
  });
}

function dispatchDeployInfra({ admin, website }) {
  const wfArgs = [
    "workflow",
    "run",
    "ci-cd.yml",
    "-f",
    `action_type=${DEPLOY_INFRA_ACTION}`,
  ];
  if (website) wfArgs.push("-f", "deploy_website=true");
  if (admin) wfArgs.push("-f", "deploy_admin=true");
  gh(wfArgs);
}

function watchLatestCiRun() {
  console.log("→ Watching latest ci-cd.yml run…");
  try {
    run("gh", ["run", "watch", "--workflow", "ci-cd.yml", "--exit-status"], { inherit: true });
  } catch {
    console.log("  Check: gh run list --workflow=ci-cd.yml");
  }
}

async function main() {
  const args = parseArgs(process.argv);
  const config = loadProcedureConfig();

  if (args.dryRun) {
  console.log(JSON.stringify(args, null, 2));
  process.exit(0);
}

if (args.fromBranch) {
  if (currentBranch() !== "main") {
    console.log("→ Checkout main…");
    run("git", ["checkout", "main"], { inherit: true });
    run("git", ["pull", "--ff-only", "origin", "main"], { inherit: true, allowFail: true });
  }
  mergeFromBranch(args.fromBranch);
}

if (currentBranch() !== "main") {
  console.error(`Must be on main (current: ${currentBranch()}). Use --from <branch> to merge first.`);
  process.exit(1);
}

assertCleanOrSyncOnly();

if (args.sync) {
  runSiteSync();
  commitSyncArtifactsIfChanged();
  assertCleanOrSyncOnly();
}

const beforeSha = shortSha("HEAD");

if (!args.skipPush) {
  console.log("→ Pushing main…");
  run("git", ["push", "origin", "main"], { inherit: true });
}

const afterSha = shortSha("HEAD");
console.log(`→ Commit ${afterSha}`);
if (beforeSha !== afterSha) {
  console.log(`  (was ${beforeSha})`);
}

console.log("→ Procedure + GitHub issue…");
const procArgs = ["scripts/procedure-init.mjs", "--title", args.title, "--branch", "main"];
if (args.component) procArgs.push("--component", args.component);
run("node", procArgs, { inherit: true });

let issueUrl = "";
try {
  const issues = gh([
    "issue",
    "list",
    "--repo",
    `${config.owner}/${config.repo}`,
    "--limit",
    "1",
    "--search",
    `in:title "${args.title}"`,
    "--json",
    "url",
  ]);
  const parsed = JSON.parse(issues || "[]");
  issueUrl = parsed[0]?.url ?? "";
} catch {
  /* optional */
}

console.log("→ Tracking PR (documents direct push on main)…");
const trackBranch = `track/direct-push-${afterSha}`;
try {
  run("git", ["fetch", "origin", "main"], { allowFail: true });
  run("git", ["branch", "-f", trackBranch, `${afterSha}~1`]);
  run("git", ["push", "origin", trackBranch, "--force"], { inherit: true });

  const prBody = [
    "## Direct main push",
    "",
    "This PR documents a fast-path push already on `main`.",
    "",
    `- **Commit:** \`${afterSha}\``,
    `- **Title:** ${args.title}`,
    issueUrl ? `- **Issue:** ${issueUrl}` : "",
    "",
    "Created by `scripts/direct-main-push.mjs` for audit trail on Project #4.",
  ]
    .filter(Boolean)
    .join("\n");

  const prUrl = gh(
    [
      "pr",
      "create",
      "--base",
      "main",
      "--head",
      trackBranch,
      "--title",
      `track: direct main push — ${args.title}`,
      "--body",
      prBody,
    ],
    { allowFail: true },
  );
  if (prUrl) console.log(`✓ Tracking PR: ${prUrl}`);
  else console.log("  (PR may already exist for this branch)");
} catch (err) {
  console.warn("⚠ Tracking PR skipped:", err instanceof Error ? err.message : err);
}

console.log("→ Sync mission-control issues to Project board…");
try {
  run("node", ["scripts/sync-mission-control-issues.mjs", "--add-to-project"], { inherit: true });
} catch (err) {
  console.warn("⚠ sync:tasks failed:", err instanceof Error ? err.message : err);
}

if (args.deployFull) {
  console.log("→ Dispatch full deploy-infra (admin + website + mail)…");
  dispatchDeployInfra({ admin: true, website: true });
  console.log("  Check: gh run list --workflow=ci-cd.yml");
} else if (args.deployWebsite) {
  console.log("→ Dispatch marketing site deploy…");
  dispatchDeployInfra({ admin: false, website: true });
  console.log("  Check: gh run list --workflow=ci-cd.yml");
}

if (args.deployAdmin) {
  console.log("→ Fast local admin deploy (CI admin-deploy also runs on push)…");
  run("npm", ["run", "admin:deploy:fast"], { inherit: true });
}

if (args.watchCi && !args.skipPush) {
  watchLatestCiRun();
} else if (!args.skipPush) {
  console.log("→ CI: push to main triggers admin-deploy when Mission Control paths change.");
  console.log("  gh run list --workflow=ci-cd.yml");
}

console.log("\n✓ Direct main push complete.");
if (issueUrl) console.log(`  Issue: ${issueUrl}`);
console.log("  Mission Control: https://cursor-dev.lorapok.tech (hard refresh if stale)");
}

const scriptPath = fileURLToPath(import.meta.url);
const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === scriptPath) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
